
--This schema has already been created in the database.
-- 1. Users
CREATE TABLE public.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    profile_image_url TEXT, bio TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Trips
CREATE TABLE public.trips (
    trip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    trip_name VARCHAR(255) NOT NULL, created_time TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Experiences
CREATE TABLE public.experiences (
    experience_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    title VARCHAR(250) NOT NULL,
    create_datetime TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    description VARCHAR(2000),
    address VARCHAR(1000) NOT NULL,
    latitude DOUBLE PRECISION, longitude DOUBLE PRECISION,
    image_url VARCHAR(2000),
    keywords VARCHAR(30)[] NOT NULL DEFAULT '{}'
);

-- 4. Ratings
CREATE TABLE public.ratings (
    experience_id BIGINT NOT NULL REFERENCES public.experiences(experience_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    PRIMARY KEY (experience_id, user_id)
);

-- 5. Trip-experience junction table
CREATE TABLE public.trip_experiences (
    trip_id BIGINT NOT NULL REFERENCES public.trips(trip_id) ON DELETE CASCADE,
    experience_id BIGINT NOT NULL REFERENCES public.experiences(experience_id) ON DELETE CASCADE,
    PRIMARY KEY (trip_id, experience_id)
);

-- 6. Password reset tokens
CREATE TABLE public.password_reset_token (
    reset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ
);

-- Indexes
CREATE INDEX idx_trips_user_id ON public.trips(user_id);

CREATE INDEX idx_experiences_user_id ON public.experiences(user_id);

CREATE INDEX idx_ratings_user_id ON public.ratings(user_id);

CREATE INDEX idx_trip_experiences_experience_id ON public.trip_experiences(experience_id);

CREATE INDEX idx_password_reset_token_user_id ON public.password_reset_token(user_id);
